#!/bin/bash
# Render `snap set villagesql <key>=<value>` into conf.d/00-snap.cnf.
# Called by the configure hook (after every `snap set`, and once after the
# services start on install) and by the install hook (so that the first
# configure run finds the file unchanged and does not restart the server).
#
# Every snap option is a server option: `snap set villagesql
# key-cache-age-threshold=500` becomes `key_cache_age_threshold = 500` under
# [mysqld] (snap option names use dashes; mysqld treats dashes and
# underscores alike). An empty value renders the bare option name, which is
# how a flag is switched on in an option file. port and bind-address always
# have a value and port is also written under [client]; port, bind-address
# and max-connections are checked here because mysqld only clamps them.
# Every other option is checked by running the candidate file through
# `mysqld --validate-config`: an unknown option or a bad value fails the
# hook, so `snap set` reports mysqld's error and the previous configuration
# stays, instead of leaving the server unable to start.
set -euo pipefail
umask 022

OUT="$SNAP_COMMON/etc/conf.d/00-snap.cnf"
MYSQLD="$SNAP/usr/bin/mysqld"

die() { echo "$*" >&2; exit 1; }

# snapctl has no "get everything" form, but an empty key names the whole
# document (which is what `snap get <snap>` asks for over the API) and
# snapctl needs two positionals to accept it. The output is the indented JSON
#   {<TAB>"": {<TAB><TAB>"<key>": <value>,...<TAB>}}
# one entry per line, or `{}` when nothing is set. snapd sorts the keys.
doc="$(snapctl get "" "")" || die "cannot read the snap options with snapctl"

declare -A opt=()   # snap key -> value as it is written to the .cnf
entry=$'^\t\t"([a-z0-9-]+)": (.*)$'
while IFS= read -r line; do
  case "$line" in
    '{'|'}'|'{}'|$'\t"": {'|$'\t}') continue ;;
  esac
  [[ "$line" =~ $entry ]] || die "cannot parse the snap options (unexpected line: $line)"
  key="${BASH_REMATCH[1]}"
  val="${BASH_REMATCH[2]%,}"
  case "$val" in
    \{*|\[*) die "$key: nested or list values are not supported, use 'snap set villagesql $key=<value>'" ;;
    null) continue ;;
    \"*\")
      val="${val:1:${#val}-2}"
      # The only characters snapd's JSON encoder escapes as \uXXXX. "$bs"
      # keeps the backslash literal in the pattern; \& is a literal & in the
      # replacement (bash 5.2+ expands a bare & to the matched text).
      bs='\'
      val="${val//"$bs"u0026/\&}"; val="${val//"$bs"u003c/<}"; val="${val//"$bs"u003e/>}"
      ;;
  esac
  case "$val" in
    *[\"\'\\\#]*|*[[:cntrl:]]*)
      die "$key: quotes, backslashes, '#' and control characters cannot be used in a snap option; put this setting in $SNAP_COMMON/etc/conf.d/<name>.cnf instead" ;;
  esac
  opt["$key"]="$val"
done <<< "$doc"

# Set on the mysqld command line by bin/mysqld.sh; a value here would be
# accepted by --validate-config and then silently ignored.
for key in datadir basedir socket pid-file log-error veb-dir; do
  [ -z "${opt[$key]+x}" ] || die "$key is fixed by the snap and cannot be changed"
done

port="${opt[port]:-3306}"
bind="${opt[bind-address]:-127.0.0.1}"

case "$port" in
  ''|*[!0-9]*) die "port must be an integer between 1 and 65535, got '$port'" ;;
esac
if [ "$port" -lt 1 ] || [ "$port" -gt 65535 ]; then
  die "port must be an integer between 1 and 65535, got '$port'"
fi
case "$bind" in
  ''|*[!A-Za-z0-9.:,*_-]*) die "bind-address contains unsupported characters: '$bind'" ;;
esac
if [ -n "${opt[max-connections]+x}" ]; then
  case "${opt[max-connections]}" in
    ''|*[!0-9]*|0) die "max-connections must be a positive integer, got '${opt[max-connections]}'" ;;
  esac
fi

# Persist the effective defaults so that `snap get villagesql` shows them.
snapctl set port="$port" bind-address="$bind"
opt[port]="$port"; opt[bind-address]="$bind"

{
  echo "# Generated by the villagesql snap from 'snap set villagesql ...'."
  echo "# Do not edit: put other settings in conf.d/<name>.cnf."
  echo "[client]"
  echo "port = $port"
  echo
  echo "[mysqld]"
  echo "port = $port"
  echo "bind_address = $bind"
  for key in $(printf '%s\n' "${!opt[@]}" | sort); do
    case "$key" in port|bind-address) continue ;; esac
    if [ -n "${opt[$key]}" ]; then
      echo "${key//-/_} = ${opt[$key]}"
    else
      echo "${key//-/_}"
    fi
  done
} > "$OUT.tmp"   # umask 022: world-readable, clients read [client] from it
# conf.d is read with !includedir, which only picks up *.cnf: the .tmp file
# is invisible to the running server.

if [ -f "$OUT" ] && [ "$(cat "$OUT.tmp")" = "$(cat "$OUT")" ]; then
  rm -f "$OUT.tmp"   # nothing changed: keep the server running
  exit 0
fi

# Validate the candidate in the context of the real my.cnf: the second include
# puts the new values after everything conf.d currently contains.
check="$(mktemp)"
trap 'rm -f "$check" "$OUT.tmp"' EXIT
printf '!include %s\n!include %s\n' "$SNAP_COMMON/etc/my.cnf" "$OUT.tmp" > "$check"
unset NOTIFY_SOCKET   # mysqld would try systemd's notify socket (see mysqld.sh)
if ! msg="$("$MYSQLD" --defaults-file="$check" --basedir="$SNAP/usr" --validate-config 2>&1)"; then
  die "mysqld rejects the new configuration, keeping the previous one:"$'\n'"$msg"
fi

mv -f "$OUT.tmp" "$OUT"

# `snapctl services` prints: Service  Startup  Current  Notes
if snapctl services villagesql.villagesql 2>/dev/null | grep -qE "^villagesql\.villagesql\s+\S+\s+active\b"; then
  snapctl restart villagesql.villagesql
fi
